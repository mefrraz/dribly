/**
 * Discover new pavilions from FPB game locations and add missing ones to Supabase.
 *
 * Scans all games_* tables for unique "local" values, cross-references with
 * the pavilions table, and inserts any missing pavilions with just the name.
 *
 * Usage:
 *   SUPABASE_URL=... SUPABASE_KEY=... node scrapers/discover-pavilions.mjs
 *
 * Set NOTIFY=true to create a GitHub Issue for new pavilions.
 */

import { createClient } from '@supabase/supabase-js'

const SUPABASE_URL = process.env.SUPABASE_URL
const SUPABASE_KEY = process.env.SUPABASE_KEY
const NOTIFY = process.env.NOTIFY === 'true'
const GH_TOKEN = process.env.GH_TOKEN || ''
const GH_REPO = 'mefrraz/dribly'

if (!SUPABASE_URL || !SUPABASE_KEY) {
    console.error('Missing SUPABASE_URL or SUPABASE_KEY')
    process.exit(1)
}

const supabase = createClient(SUPABASE_URL, SUPABASE_KEY)

// ── Fetch all unique game locations ────────────────────

const GAME_TABLES = ['games_2025_2026', 'games_2024_2025', 'games_2023_2024', 'games_2022_2023']

console.log('🔍 Scanning game locations...')
const allLocals = new Set<string>()
for (const table of GAME_TABLES) {
    let from = 0
    const PAGE = 1000
    while (true) {
        const { data } = await supabase.from(table).select('local').range(from, from + PAGE - 1).not('local', 'is', null)
        if (!data || data.length === 0) break
        for (const row of data) {
            const loc = (row.local || '').trim()
            if (loc && loc.length > 2) allLocals.add(loc)
        }
        if (data.length < PAGE) break
        from += PAGE
    }
}
console.log(`  Found ${allLocals.size} unique game locations`)

// ── Fetch existing pavilion names ──────────────────────

const { data: existing } = await supabase.from('pavilions').select('id, nome')
const existingNames = new Set((existing || []).map(p => p.nome.toLowerCase().trim()))
console.log(`  ${existingNames.size} pavilions already in database`)

// ── Find new pavilions ────────────────────────────────

const newPavilions: string[] = []
for (const loc of allLocals) {
    const norm = loc.toLowerCase().trim()
    // Check exact match or substring
    let found = existingNames.has(norm)
    if (!found) {
        for (const en of existingNames) {
            if (en.includes(norm) || norm.includes(en)) { found = true; break }
        }
    }
    if (!found) newPavilions.push(loc)
}

console.log(`\n📋 ${newPavilions.length} NEW pavilions found:`)
newPavilions.slice(0, 30).forEach(n => console.log(`  • ${n}`))
if (newPavilions.length > 30) console.log(`  ... and ${newPavilions.length - 30} more`)

// ── Insert into Supabase ───────────────────────────────

if (newPavilions.length > 0) {
    console.log('\n💾 Inserting into Supabase...')
    let inserted = 0
    for (const nome of newPavilions) {
        const { error } = await supabase.from('pavilions').insert({ nome, geocode_ok: false })
        if (error) {
            if (error.code === '23505') continue // duplicate
            console.log(`  ❌ ${nome}: ${error.message}`)
        } else {
            inserted++
            console.log(`  ✅ ${nome}`)
        }
    }
    console.log(`\n🏁 ${inserted} new pavilions inserted.`)
}

// ── Notify via GitHub Issue ────────────────────────────

if (NOTIFY && newPavilions.length > 0 && GH_TOKEN) {
    const body = `## 🏟️ ${newPavilions.length} novos pavilhões descobertos

Estes pavilhões aparecem em jogos mas não estão na base de dados:

${newPavilions.map(n => `- ${n}`).join('\n')}

### O que fazer
1. Ir a [Admin → Pavilhões](https://dribly.pt/admin/pavilhoes)
2. Preencher morada, coordenadas e fotos
3. Usar o botão **Geo** para geocodificar

_Auto-generated by discover-pavilions script_`

    const res = await fetch(`https://api.github.com/repos/${GH_REPO}/issues`, {
        method: 'POST',
        headers: {
            'Authorization': `Bearer ${GH_TOKEN}`,
            'Content-Type': 'application/json',
            'User-Agent': 'Dribly-Bot',
        },
        body: JSON.stringify({
            title: `🏟️ ${newPavilions.length} novos pavilhões para rever`,
            body,
            labels: ['pavilions', 'data'],
        }),
    })
    if (res.ok) {
        const issue = await res.json()
        console.log(`\n📬 GitHub Issue criada: ${issue.html_url}`)
    } else {
        console.log(`\n❌ Failed to create issue: ${res.status} ${await res.text()}`)
    }
} else if (NOTIFY && !GH_TOKEN) {
    console.log('\n⚠️  NOTIFY=true mas GH_TOKEN não definido.')
}
